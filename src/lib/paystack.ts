/**
 * Create a new Paystack transaction and return the checkout URL.
 *
 * @example
 * const { authorization_url, reference } = await initializePayment({
 *   email: "customer@example.com",
 *   amount_kobo: 350_000,   // KES 3,500
 *   reference: "hkh_1234_abc",
 *   metadata: { bookingId: "uuid-here" },
 * });
 */
export async function initializePayment(
  params: InitializePaymentParams
): Promise<InitializePaymentResult> {
  return paystackFetch<InitializePaymentResult>(
    "/transaction/initialize",
    {
      method: "POST",
      body: JSON.stringify({
        email: params.email,
        amount: params.amount_kobo,
        reference: params.reference,
        currency: "KES",
        callback_url: `${process.env.NEXT_PUBLIC_APP_URL ?? "https://hookah-website-two.vercel.app"}/booking/confirm`,
        ...(params.metadata ? { metadata: params.metadata } : {}),
      }),
    }
  );
}

/**
 * Verify a transaction by reference. Call after redirect from Paystack or
 * in the webhook handler.
 *
 * @throws if the HTTP request fails or Paystack returns status=false
 * @returns Raw transaction data — check `.status === "success"` yourself.
 */
export async function verifyPayment(
  reference: string
): Promise<PaystackTransactionData> {
  return paystackFetch<PaystackTransactionData>(
    `/transaction/verify/${encodeURIComponent(reference)}`
  );
}
